"""识别模块：YOLO 单模型四类检测 API（已实现返回数据功能）。

职责口径（已定）：一个 YOLO 模型，一次推理返回四类标签——
魔方/球/盆/桶；代码只做"加载模型 → 识别 → 返回数据"，结果由调用方
处理，本模块不入库、不存队列。

已实现（state.py / model.py / detector.py）：
  1. RoiTarget（state.py）：识别目标的 ROI 数据——外接框 bbox +
     ROI 中点 center，魔方/球/盆/桶通用一个结构（拿到哪个列表/
     单例就知道品类）
  2. 模型加载与推理（model.py）：单模型懒加载（进程内缓存一次），
     一次推理输出全部四类原始检测（类别名/外接框/置信度）；
     权重路径 models/cube_ball.pt、类别名、置信度阈值 0.8 为模块
     常量，权重训练好放到该路径即可跑通
  3. 检测 API（detector.detect）：对一帧推理，返回
     (魔方列表, 球列表, 盆, 桶)——
     - 魔方、球：场上多个，列表存储，每项 RoiTarget
     - 盆、桶：单次投放任务里各只有一个，不列表——识别到多处取
       置信度最高的一处，没识别到为 None
     - 置信度 ≥ 阈值才认定品类；纯函数只 return，不入库不存队列

  4. 六色色块工具（color_blob.py，挪用上一版实现，已实现）：
     find_color_blobs(frame, color, min_area) 按六色 BGR 区间找色块
     （形态学开闭去噪、按面积降序）；dominant_color(frame, bbox)
     判某 ROI 主色（色块总面积最大者，判不出返回 None）。
     两个用途共用：不同颜色的球（评分颜色因子）、桶底颜色（第一次
     投放后建颜色↔桶映射，路径见 docs/扩展功能技术路线.md）；区间
     数值现场光照下直接改

识别结果不入库：RuntimeData 预留了 cube_queue / ball_queue（每项 =
一帧的该品类目标列表，长度 16），由调用方自行按帧放入，供 M 帧防抖、
评分取用。
"""
